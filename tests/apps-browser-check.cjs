// Issue #8 browser acceptance checks. Serve the repo first, then run with
// PLAYWRIGHT_MODULE=/path/to/playwright node tests/apps-browser-check.cjs.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.APPS_BASE_URL || 'http://127.0.0.1:4187';

(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-gpu'] });
  try {
    for (const width of [1440, 900, 390, 320]) {
      const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.addInitScript(() => {
        window.copied = [];
        Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => window.copied.push(text) } });
      });
      await page.goto(base + '/apps/', { waitUntil: 'networkidle' });
      assert.equal(await page.locator('details.sec').count(), 0);
      assert.equal(await page.locator('.app-section .apps:visible').count(), await page.locator('.app-section').count());
      const expected = await page.locator('#apps-data').evaluate(el => JSON.parse(el.textContent));
      assert.equal(await page.locator('article.app').count(), expected.apps.length);
      assert.equal(await page.locator('.evidence-fold[open]:visible').count(), 0);
      assert.equal(await page.locator('#nodejs .validation-shot').count(), 0);
      assert.equal(await page.locator('.app-head .badge, .app-head .validation-shot').count(), 0);
      assert.equal(await page.locator('#brave .more > summary').textContent(), 'Passing');
      assert.match(await page.locator('#brave .more > summary').getAttribute('aria-label'), /Passing.*Details for Brave/);
      const columns = await page.locator('.apps').first().evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length);
      assert.equal(columns, width === 1440 ? 3 : width === 900 ? 2 : 1);
      const app = page.locator('#brave');
      const neighbor = page.locator('#telegram');
      await app.scrollIntoViewIfNeeded();
      const closed = await app.boundingBox();
      assert(closed.height <= (width > 640 ? 90 : 126), `closed row too tall at ${width}: ${closed.height}`);
      assert.equal(await app.locator('.app-desc').isVisible(), false);
      const oldWidth = (await neighbor.boundingBox()).width;
      const layout = () => page.locator('article.app').evaluateAll(nodes => nodes.map(node => {
        const box = node.getBoundingClientRect();
        return [node.id, box.x, box.y + scrollY, box.width, box.height];
      }));
      const positions = await layout();
      const pageHeight = await page.evaluate(() => document.documentElement.scrollHeight);
      const details = page.locator('#app-details');
      const detailsTrigger = app.locator('.more > summary');
      await detailsTrigger.hover();
      await details.waitFor({ state: 'visible' });
      const hoverTitle = await details.locator('h3').boundingBox();
      const hoverPanel = await details.boundingBox();
      assert(Math.abs(hoverPanel.width - closed.width * 0.8) < 1 && Math.abs(hoverPanel.x + hoverPanel.width - closed.x - closed.width) < 1);
      assert(await details.locator('.details-content').isVisible(), 'hover must show full Details immediately');
      assert(await details.locator('.dist').isVisible(), 'hover must show Package source');
      assert(await details.locator('.validation-shot').isVisible(), 'Test run belongs inside Details');
      assert.match(await details.locator('.validation-shot').getAttribute('href'), /app-shots/);
      assert.match(await details.locator('.validation-shot img').getAttribute('alt'), /automated Omnix test/);
      assert.equal(await details.locator('.details-more').count(), 0, 'extra expansion step remains');
      await page.mouse.move(hoverTitle.x + 5, hoverTitle.y + 5, { steps: 8 });
      await page.waitForTimeout(260);
      assert(await details.isVisible(), 'Details closes while moving into its dropdown');
      await page.mouse.move(1, 880);
      await page.waitForTimeout(260);
      assert.equal(await details.isVisible(), false, 'unpinned Details stays open after leaving');
      await detailsTrigger.hover();
      await details.hover();
      const beforeWheel = await page.evaluate(() => scrollY);
      await page.mouse.wheel(0, 60);
      await page.waitForTimeout(250);
      assert(await details.isVisible(), 'scrolling down dismisses hovered Details');
      await page.mouse.wheel(0, -60);
      await page.waitForTimeout(250);
      assert(await details.isVisible(), 'scrolling up dismisses hovered Details');
      await page.evaluate(() => window.scrollBy(0, 20));
      await page.waitForTimeout(250);
      assert(await details.isVisible(), 'page scrolling dismisses hovered Details');
      const scrollCard = await app.boundingBox(), scrollPanel = await details.boundingBox();
      assert(Math.abs(scrollPanel.y - scrollCard.y - scrollCard.height - 6) < 1 || Math.abs(scrollPanel.y + scrollPanel.height - scrollCard.y + 6) < 1, 'scrolling detaches Details from its card');
      await page.mouse.move(1, 880);
      await page.waitForTimeout(260);
      assert.equal(await details.isVisible(), false, 'scrolling permanently pins hovered Details after mouse-out');
      await detailsTrigger.evaluate(el => el.blur());
      await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), beforeWheel);
      await page.mouse.move(1, 880);
      // Each genuine re-entry must open immediately, even after delayed dismissal.
      for (let attempt = 0; attempt < 3; attempt++) {
        await detailsTrigger.hover();
        assert(await details.isVisible(), 'Details requires a second hover after mouse-out');
        await page.mouse.move(1, 880);
        await page.waitForTimeout(260);
        assert.equal(await details.isVisible(), false);
      }
      await detailsTrigger.focus();
      assert(await details.isVisible(), 'keyboard focus opens Details');
      await page.keyboard.press('Escape');
      await page.waitForTimeout(260);
      assert.equal(await details.isVisible(), false, 'Escape immediately reopens Details');
      await detailsTrigger.click();
      assert(await details.isVisible());
      assert(await details.locator('.app-desc').isVisible(), 'one Details click must expand the full dropdown');
      assert((await details.boundingBox()).height > closed.height, 'Details does not show full menu');
      await page.mouse.move(1, 880);
      await page.waitForTimeout(260);
      assert(await details.isVisible(), 'click does not pin Details');
      assert.deepEqual(await layout(), positions, 'opening Details moves app cards');
      assert.equal(await page.evaluate(() => document.documentElement.scrollHeight), pageHeight);
      const panel = await details.boundingBox();
      assert(panel.x >= 0 && panel.x + panel.width <= width + 1 && panel.y >= 0 && panel.y + panel.height <= 901);
      assert.equal(await details.locator('h3').textContent(), 'Brave 1.96.61');
      assert.equal(await details.locator('.details-app-icon').count(), 1);
      assert.equal(await details.locator('.validation-date time').getAttribute('datetime'), '2026-10-06');
      assert.equal(await details.locator('.validation-date').evaluate(el => getComputedStyle(el).whiteSpace), 'nowrap');
      assert((await details.locator('.evidence-fold > summary').first().boundingBox()).height >= 44);
      assert(Math.abs(panel.x + panel.width - closed.x - closed.width) < 1 && Math.abs(panel.width - closed.width * 0.8) < 1, 'expanded Details is not 80% width and right aligned');
      assert(Math.abs(panel.y - (closed.y + closed.height + 6)) < 1 || Math.abs(panel.y + panel.height - (closed.y - 6)) < 1, 'Details is not anchored above/below its app card');
      await page.evaluate(() => window.scrollBy(0, 20));
      await page.waitForTimeout(100);
      const movedCard = await app.boundingBox();
      const movedPanel = await details.boundingBox();
      assert(Math.abs(movedPanel.y - (movedCard.y + movedCard.height + 6)) < 1 || Math.abs(movedPanel.y + movedPanel.height - (movedCard.y - 6)) < 1, 'Details loses its anchor when scrolling');
      await page.evaluate(() => window.scrollBy(0, -20));
      await page.waitForTimeout(100);
      assert.equal((await app.boundingBox()).width, closed.width);
      assert.equal((await neighbor.boundingBox()).width, oldWidth);
      assert.equal(await details.locator('.steps').isVisible(), false);
      for (const label of ['Install', 'Verified workflow', 'Validation details', 'Package source']) {
        const fold = details.locator('.evidence-fold').filter({ has: page.locator('summary', { hasText: label }) }).first();
        if (await fold.getAttribute('open') !== null) await fold.locator(':scope > summary').click();
        await fold.locator(':scope > summary').click();
        assert.equal(await fold.getAttribute('open'), '');
        if (label === 'Validation details') {
          const row = fold.locator('.evidence > div').first();
          const labelBox = await row.locator('dt').boundingBox();
          const valueBox = await row.locator('dd').boundingBox();
          assert(Math.abs(valueBox.x - labelBox.x) < 1 && Math.abs(valueBox.width - labelBox.width) < 1, 'evidence wastes width on a label column');
          assert(valueBox.y >= labelBox.y + labelBox.height - 1, 'evidence label must sit above its full-width value');
        }
        if (label === 'Install') {
          await fold.locator('.copy').click();
          assert.equal(await page.evaluate(() => window.copied[0]), await fold.locator('pre').textContent());
        }
        await fold.locator(':scope > summary').click();
      }
      await details.locator('.evidence-fold, .run-log').evaluateAll(nodes => nodes.forEach(node => { node.open = true; }));
      assert.deepEqual(await layout(), positions, 'expanding evidence moves app cards');
      assert.equal(await details.evaluate(el => el.scrollWidth > el.clientWidth), false);
      await details.evaluate(el => { el.scrollTop = 0; });
      await details.hover();
      const documentBeforeEvidenceScroll = await page.evaluate(() => scrollY);
      await page.mouse.wheel(0, 80);
      await page.waitForTimeout(200);
      assert(await details.isVisible(), 'scrolling long evidence dismisses Details');
      assert(await details.evaluate(el => el.scrollTop) > 0, 'long evidence does not scroll');
      assert.equal(await page.evaluate(() => scrollY), documentBeforeEvidenceScroll, 'scrolling evidence moves the page');
      await page.mouse.wheel(0, -80);
      await page.waitForTimeout(200);
      assert(await details.isVisible(), 'scrolling evidence upward dismisses Details');
      await page.keyboard.press('Escape');
      assert.equal(await details.isVisible(), false);
      assert.equal(await app.locator('.more > summary').evaluate(el => el === document.activeElement), true);
      const beforeReopen = await page.evaluate(() => scrollY);
      await app.locator('.more > summary').click();
      assert.equal(await page.evaluate(() => scrollY), beforeReopen, 'reopening Details scrolls the page');
      await details.locator('.details-close').click();
      assert.equal(await details.isVisible(), false);
      await app.locator('.more > summary').click();
      await page.mouse.click(1, 1);
      assert.equal(await details.isVisible(), false, 'outside click closes Details');
      await app.locator('.more > summary').click();
      await app.locator('.more > summary').click();
      assert.equal(await details.isVisible(), false, 'Details trigger toggles its dropdown');
      assert.deepEqual(await layout(), positions, 'closing Details moves app cards');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      assert.deepEqual(errors, []);
      console.log(JSON.stringify({ width, closedHeight: closed.height, anchoredDetailsWithoutReflow: true, detailsHoverTransfer: true, fullDetailsOnHover: true, singleClickPin: true, hoverSurvivesScrolling: true, hover: true, keyboard: true, copy: true, overflow: false }));
      await page.close();
    }
    const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await touch.goto(base + '/apps/', { waitUntil: 'networkidle' });
    await touch.locator('#brave').scrollIntoViewIfNeeded();
    await touch.locator('#brave .more > summary').tap();
    assert(await touch.locator('#app-details').isVisible());
    assert(await touch.locator('#app-details .details-content').isVisible(), 'one tap must expand Details');
    await touch.locator('.details-close').tap();
    assert.equal(await touch.locator('#app-details').isVisible(), false);
    await touch.locator('#brave .more > summary').tap();
    assert(await touch.locator('#app-details .validation-shot').isVisible());
    await touch.locator('.details-close').tap();
    await touch.close();
    const nojs = await browser.newPage({ javaScriptEnabled: false });
    await nojs.goto(base + '/apps/', { waitUntil: 'networkidle' });
    assert.equal(await nojs.locator('.validation-shot:visible').count(), 0);
    await nojs.locator('#brave .more > summary').click();
    await nojs.locator('#brave .evidence-fold > summary', { hasText: 'Validation details' }).click();
    assert(await nojs.locator('#brave .validation-caption a').isVisible());
    await nojs.close();
    const fallback = await browser.newPage();
    await fallback.addInitScript(() => { HTMLElement.prototype.showPopover = undefined; });
    await fallback.goto(base + '/apps/', { waitUntil: 'networkidle' });
    await fallback.locator('#brave').scrollIntoViewIfNeeded();
    await fallback.locator('#brave .more > summary').click();
    assert(await fallback.locator('#app-details').isVisible());
    await fallback.keyboard.press('Escape');
    assert.equal(await fallback.locator('#app-details').isVisible(), false);
    await fallback.locator('#brave .more > summary').click();
    assert(await fallback.locator('#app-details .validation-shot').isVisible());
    await fallback.keyboard.press('Escape');
    await fallback.close();
    console.log(JSON.stringify({ touch: true, withoutJavaScript: true, withoutPopoverAPI: true }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
